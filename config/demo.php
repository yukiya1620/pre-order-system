<?php

return [

    /*
    |--------------------------------------------------------------------------
    | 一般公開デモモード
    |--------------------------------------------------------------------------
    |
    | true の場合のみ、後述のホワイトリストに登録された電話番号に限り、
    | SMS認証コードをAPIレスポンスへ含める(閲覧者がSMS認証を体験できるようにするため)。
    | 実際のSMS送信は行わず、SmsSenderの実装は変更しない。
    | 通常の本番環境では必ず false(未設定)のままにすること。
    |
    */

    'enabled' => (bool) env('DEMO_MODE', false),

    /*
    |--------------------------------------------------------------------------
    | デモ用電話番号ホワイトリスト
    |--------------------------------------------------------------------------
    |
    | ここに登録された電話番号以外には、DEMO_MODE=true であっても
    | 認証コードを絶対にレスポンスへ含めない。
    | .envでは "00000000001,00000000002" のようにカンマ区切りで指定する。
    |
    */

    'sms_phone_numbers' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('DEMO_SMS_PHONE_NUMBERS', ''))
    ))),

    /*
    |--------------------------------------------------------------------------
    | チュートリアル案内用のデモ購入者電話番号
    |--------------------------------------------------------------------------
    |
    | 一般公開デモの操作チュートリアル(購入者ログイン案内)が画面に表示する、
    | 実際にログインできるデモ用電話番号。ここで設定した値は、
    | 上記 sms_phone_numbers に含めておくこと(含めないと、この番号を
    | 案内してもSMS認証コードが画面に表示されず、体験できない)。
    | また PortfolioDemoSeeder が作成する購入者アカウントの電話番号
    | (1〜5をゼロ埋めした11桁)のいずれかと一致させておくこと。
    |
    | DEMO_MODE=true の場合だけ、Bladeがこの値をそのままチュートリアルの
    | 案内文へ出力する(JS・Bladeへ値を直接書き込むことはしない)。
    | 未設定(null)の場合、チュートリアルは電話番号を案内しない。
    |
    */

    'tutorial_buyer_phone' => env('DEMO_TUTORIAL_BUYER_PHONE'),

];
