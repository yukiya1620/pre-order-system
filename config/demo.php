    | 認証処理そのもの(メール+パスワードログインAPI)は一切変更しない。
    | 未設定(null)の場合、チュートリアルは販売者デモ案内を表示しない。
    |
    */

    'tutorial_farmer_email' => env('DEMO_TUTORIAL_FARMER_EMAIL'),
    'tutorial_farmer_password' => env('DEMO_TUTORIAL_FARMER_PASSWORD'),

